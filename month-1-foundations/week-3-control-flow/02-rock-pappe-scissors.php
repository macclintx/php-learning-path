<?php

    /*
        What it does : creates a rock paper scissors game using interactive loop for a user against a computer
        What is assume: assume random numbers generated by computer 1,2,3 are rock, paper, scissors respectively
        What breaks: Simply set the condition of the while loop to use 'yes' for confirmation
                     otherwise the loop will not end when user inputs an invalid confirmation(neither yes or no)
    */ 
    do{
        echo "\nRock Paper Scissors against Computer\n\n";
        $computer_input = random_int(1,3);
        $user_input = readline("Enter option (rock, paper, scissors): ");

        $user_input = trim(strtolower($user_input));

        if($computer_input === 1 && $user_input === 'rock'){
            echo "Computer: Rock\nDraw\n";
        }elseif($computer_input === 1 && $user_input === 'paper'){
            echo "Computer: Rock\nUser Wins\n";
        }elseif($computer_input === 1 && $user_input === 'scissors'){
            echo "Computer: Rock\nComputer Wins\n";
        }elseif($computer_input === 2 && $user_input === 'rock'){
            echo "Computer: Paper\nComputer Wins\n";
        }elseif($computer_input === 2 && $user_input === 'paper'){
            echo "Computer: Paper\nDraw\n";
        }elseif($computer_input === 2 && $user_input === 'scissors'){
            echo "Computer: Paper\nUser Wins\n";
        }elseif($computer_input === 3 && $user_input === 'rock'){
            echo "Computer: Scissors\nUser Wins\n";
        }elseif($computer_input === 3 && $user_input === 'paper'){
            echo "Computer: Scissors\nComputer Wins\n";
        }elseif($computer_input === 3 && $user_input === 'scissors'){
            echo "Computer: Scissors\nDraw\n";
        }else{
            echo "Invalid input!\n";
        }


        $confirm_play = readline("Do you want to continue playing(yes or no)");
        $confirm_play_trim = trim(strtolower($confirm_play));
    
        if($confirm_play_trim !== 'no' && $confirm_play_trim !== 'yes' ){
            echo ("Invalid confirmation choice! (yes or no)\n");
        }
 
        
    }while($confirm_play_trim === 'yes' );
    echo "ByeBye! :)\n";